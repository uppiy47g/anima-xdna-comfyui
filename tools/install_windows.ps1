[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [ValidateSet("standard", "int8")]
    [string]$RuntimeProfile,
    [string]$WheelDirectory,
    [string]$InstallRoot = (Join-Path $env:USERPROFILE "ComfyUI-AnimaXDNA"),
    [string]$RuntimeBundlePath,
    [string]$XrtSdkDirectory,
    [string]$PythonExe,
    [string]$ModelsDirectory,
    [ValidateRange(1, 256)]
    [int]$NumThreads,
    [switch]$SkipChecks
)

# One-shot Windows installer: ComfyUI (pinned) + CPU PyTorch + Triton-XDNA
# toolchain + this custom node + XRT SDK, configured for Comfy Desktop's
# "Add Existing Instance" and for the run-xdna.ps1 launcher.

$ErrorActionPreference = "Stop"
$ProgressPreference = "SilentlyContinue"

$comfyRepository = "https://github.com/comfyanonymous/ComfyUI.git"
$comfyCommit = "170594057a22673349ddf0a3d88624b7fa5865bb"
$torchIndex = "https://download.pytorch.org/whl/cpu"
$xrtVersion = "2.21.75"
$xrtSdkUrl = "https://github.com/Xilinx/XRT/releases/download/$xrtVersion/xrt_windows_sdk.zip"
$xrtSdkSha256 = "ccc244c2c423588972ade76142cdc01049477aaa39a35be97e782b97eb7c5295"
$toolchainPackages = @("triton-xdna", "mlir-air", "mlir-aie-no-rtti", "llvm-aie")
$generatedMarker = "Generated by anima-xdna-comfyui tools/install_windows.ps1"
$desktopArguments = "--cpu --listen 127.0.0.1 --port 8190 --disable-auto-launch --preview-method none --cache-classic"

$sourceRoot = (Resolve-Path -LiteralPath (Join-Path $PSScriptRoot "..")).Path
$constraints = Join-Path $PSScriptRoot "windows-cp313-constraints.txt"
$comfyPatch = Join-Path $PSScriptRoot "patches\comfyui-170594057-mimalloc-after-torch.patch"
$workflowSource = Join-Path $sourceRoot "examples\workflows\anima_xdna_cache_backed_1024.json"
$utf8 = New-Object System.Text.UTF8Encoding $false

function Write-Step([string]$Message) {
    Write-Host ""
    Write-Host "==> $Message" -ForegroundColor Cyan
}

function Invoke-Checked([string]$FilePath, [string[]]$Arguments, [string]$Activity) {
    & $FilePath @Arguments | Out-Host
    if ($LASTEXITCODE -ne 0) {
        throw "$Activity failed with exit code $LASTEXITCODE."
    }
}

function Test-Native([string]$FilePath, [string[]]$Arguments) {
    $ErrorActionPreference = "Continue"
    & $FilePath @Arguments 2>$null | Out-Null
    return ($LASTEXITCODE -eq 0)
}

function Get-PythonVersion([string]$Executable) {
    $ErrorActionPreference = "Continue"
    $output = & $Executable -c "import struct,sys;print('%d.%d %d' % (sys.version_info[0], sys.version_info[1], struct.calcsize('P') * 8))" 2>$null
    if ($LASTEXITCODE -ne 0) {
        return $null
    }
    return ([string]$output).Trim()
}

function Resolve-Python {
    if ($PythonExe) {
        $candidate = (Resolve-Path -LiteralPath $PythonExe).Path
    }
    else {
        $candidate = $null
        if (Get-Command py -ErrorAction SilentlyContinue) {
            $ErrorActionPreference = "Continue"
            $found = & py -3.13 -c "import sys;print(sys.executable)" 2>$null
            if ($LASTEXITCODE -eq 0 -and $found) {
                $candidate = ([string]$found).Trim()
            }
            $ErrorActionPreference = "Stop"
        }
        if (-not $candidate) {
            $python = Get-Command python -ErrorAction SilentlyContinue
            if ($python) {
                $candidate = $python.Source
            }
        }
    }
    if (-not $candidate -or (Get-PythonVersion $candidate) -ne "3.13 64") {
        throw "64-bit Python 3.13 is required (python.org installer, with the py launcher). " +
            "Install it or pass -PythonExe <path to python.exe>."
    }
    return $candidate
}

function Test-MsvcAvailable {
    if (Get-Command cl.exe -ErrorAction SilentlyContinue) {
        return $true
    }
    $vswhere = Join-Path ${env:ProgramFiles(x86)} "Microsoft Visual Studio\Installer\vswhere.exe"
    if (-not (Test-Path -LiteralPath $vswhere -PathType Leaf)) {
        return $false
    }
    $ErrorActionPreference = "Continue"
    $path = & $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath 2>$null
    return [bool]$path
}

function Get-ConstraintVersions {
    $versions = @{}
    foreach ($line in [System.IO.File]::ReadAllLines($constraints)) {
        if ($line -match "^([A-Za-z0-9_.\-]+)==(\S+)$") {
            $versions[$Matches[1].ToLowerInvariant()] = $Matches[2]
        }
    }
    return $versions
}

function Test-XrtSdk([string]$Directory) {
    return (Test-Path -LiteralPath (Join-Path $Directory "include\xrt") -PathType Container) -and
        (Test-Path -LiteralPath (Join-Path $Directory "lib") -PathType Container) -and
        (Test-Path -LiteralPath (Join-Path $Directory "python\pyxrt.pyd") -PathType Leaf)
}

function Install-XrtSdk([string]$Destination) {
    $amdRoot = Split-Path -Parent $Destination
    New-Item -ItemType Directory -Path $amdRoot -Force | Out-Null
    $staging = Join-Path $amdRoot (".xrt-staging-" + [guid]::NewGuid().ToString("N"))
    New-Item -ItemType Directory -Path $staging | Out-Null
    try {
        $archive = Join-Path $staging "xrt_windows_sdk.zip"
        Write-Host "Downloading XRT SDK $xrtVersion"
        Invoke-WebRequest -Uri $xrtSdkUrl -OutFile $archive -UseBasicParsing
        $hash = (Get-FileHash -LiteralPath $archive -Algorithm SHA256).Hash.ToLowerInvariant()
        if ($hash -ne $xrtSdkSha256) {
            throw "XRT SDK SHA-256 mismatch: $hash"
        }
        Add-Type -AssemblyName System.IO.Compression.FileSystem
        [System.IO.Compression.ZipFile]::ExtractToDirectory($archive, (Join-Path $staging "x"))
        $extracted = Join-Path $staging "x\xrt_sdk\xrt"
        if (-not (Test-XrtSdk $extracted)) {
            throw "Unexpected XRT SDK archive layout."
        }
        Move-Item -LiteralPath $extracted -Destination $Destination
    }
    finally {
        Remove-Item -LiteralPath $staging -Recurse -Force -ErrorAction SilentlyContinue
    }
}

function Write-GeneratedFile([string]$Path, [string]$Content) {
    if (Test-Path -LiteralPath $Path -PathType Leaf) {
        $existing = [System.IO.File]::ReadAllText($Path)
        if (-not $existing.Contains($generatedMarker)) {
            Write-Warning "Keeping existing file that was not created by this installer: $Path"
            return
        }
    }
    [System.IO.File]::WriteAllText($Path, $Content, $utf8)
}

# --- Preflight -------------------------------------------------------------
Write-Step "Checking prerequisites"
if (-not [Environment]::Is64BitOperatingSystem) {
    throw "64-bit Windows is required."
}
if (-not (Test-Path -LiteralPath (Join-Path $env:SystemRoot "System32\AMD\xrt-smi.exe") -PathType Leaf)) {
    throw "The AMD NPU driver was not found (System32\AMD\xrt-smi.exe). Install the AMD Ryzen AI NPU driver first."
}
if (-not (Get-Command git -ErrorAction SilentlyContinue)) {
    throw "Git for Windows is required."
}
if (-not (Test-MsvcAvailable)) {
    throw "MSVC was not found. Install Visual Studio 2022 Build Tools with the " +
        "'Desktop development with C++' workload; Triton-XDNA compiles its launcher with it."
}
foreach ($path in @($constraints, $comfyPatch, $workflowSource)) {
    if (-not (Test-Path -LiteralPath $path -PathType Leaf)) {
        throw "Installer file is missing: $path"
    }
}
$basePython = Resolve-Python
Write-Host "Python: $basePython"
$versions = Get-ConstraintVersions
if ($InstallRoot -match "[^\x20-\x7E]") {
    Write-Warning "InstallRoot contains non-ASCII characters; native toolchains may fail. Prefer an ASCII path."
}
$InstallRoot = [System.IO.Path]::GetFullPath($InstallRoot)
$venv = Join-Path $InstallRoot ".venv"
$venvPython = Join-Path $venv "Scripts\python.exe"

$toolchainInstalled = $false
if (Test-Path -LiteralPath $venvPython -PathType Leaf) {
    $toolchainInstalled = Test-Native $venvPython @(
        "-c", "import importlib.metadata as m,sys;sys.exit(m.version('triton-xdna')!='$($versions['triton-xdna'])')"
    )
}
if ($WheelDirectory) {
    $WheelDirectory = (Resolve-Path -LiteralPath $WheelDirectory).Path
    $missing = @()
    foreach ($package in $toolchainPackages) {
        $prefix = $package.Replace("-", "_") + "-" + $versions[$package] + "-"
        $wheel = Get-ChildItem -LiteralPath $WheelDirectory -File |
            Where-Object { $_.Name.StartsWith($prefix, [System.StringComparison]::OrdinalIgnoreCase) -and $_.Name.EndsWith(".whl") }
        if (-not $wheel) {
            $missing += "$($prefix)*.whl"
        }
    }
    if ($missing) {
        throw "WheelDirectory is missing the validated toolchain wheels:`n  " + ($missing -join "`n  ")
    }
}
elseif (-not $toolchainInstalled) {
    throw "-WheelDirectory is required: supply the four validated Triton-XDNA toolchain wheels."
}

# --- ComfyUI ---------------------------------------------------------------
Write-Step "Preparing ComfyUI $($comfyCommit.Substring(0, 9)) in $InstallRoot"
if (Test-Path -LiteralPath (Join-Path $InstallRoot "main.py") -PathType Leaf) {
    $ErrorActionPreference = "Continue"
    $head = & git -C $InstallRoot rev-parse HEAD 2>$null
    $ErrorActionPreference = "Stop"
    if ($head -ne $comfyCommit) {
        throw "$InstallRoot is a different ComfyUI checkout. Choose a new -InstallRoot; only commit $comfyCommit is supported."
    }
}
elseif ((Test-Path -LiteralPath $InstallRoot) -and (Get-ChildItem -LiteralPath $InstallRoot -Force | Select-Object -First 1)) {
    throw "InstallRoot exists and is not empty: $InstallRoot"
}
else {
    Invoke-Checked git @("clone", $comfyRepository, $InstallRoot) "Cloning ComfyUI"
    Invoke-Checked git @("-C", $InstallRoot, "-c", "advice.detachedHead=false", "checkout", "--detach", $comfyCommit) "Checking out ComfyUI"
}
if (Test-Native git @("-C", $InstallRoot, "apply", "--reverse", "--check", $comfyPatch)) {
    Write-Host "ComfyUI startup patch already applied."
}
else {
    Invoke-Checked git @("-C", $InstallRoot, "apply", $comfyPatch) "Applying the ComfyUI startup patch"
}

# --- Python environment ----------------------------------------------------
Write-Step "Creating the Python 3.13 environment"
if (Test-Path -LiteralPath $venvPython -PathType Leaf) {
    if ((Get-PythonVersion $venvPython) -ne "3.13 64") {
        throw "Existing $venv is not 64-bit Python 3.13. Remove it and run the installer again."
    }
}
else {
    Invoke-Checked $basePython @("-m", "venv", $venv) "Creating the virtual environment"
}
$pip = @("-m", "pip", "install", "--disable-pip-version-check", "-c", $constraints)
Invoke-Checked $venvPython ($pip + @("pip")) "Updating pip"

Write-Step "Installing CPU PyTorch"
Invoke-Checked $venvPython ($pip + @("--index-url", $torchIndex, "--extra-index-url", "https://pypi.org/simple", "torch", "torchvision")) "Installing PyTorch"

Write-Step "Installing the Triton-XDNA toolchain"
if ($WheelDirectory) {
    Invoke-Checked $venvPython ($pip + @("--find-links", $WheelDirectory) + $toolchainPackages) "Installing the toolchain wheels"
}

Write-Step "Installing ComfyUI requirements"
Invoke-Checked $venvPython ($pip + @("-r", (Join-Path $InstallRoot "requirements.txt"))) "Installing ComfyUI requirements"

# --- Custom node -----------------------------------------------------------
Write-Step "Installing the Anima XDNA custom node"
$nodeRoot = Join-Path $InstallRoot "custom_nodes\anima-xdna-comfyui"
if (-not [string]::Equals($sourceRoot.TrimEnd("\"), $nodeRoot, [System.StringComparison]::OrdinalIgnoreCase)) {
    if (Test-Path -LiteralPath (Join-Path $sourceRoot ".git")) {
        $files = & git -C $sourceRoot -c core.quotepath=off ls-files --cached --others --exclude-standard
        if ($LASTEXITCODE -ne 0) {
            throw "Listing the custom node files failed."
        }
    }
    else {
        $files = Get-ChildItem -LiteralPath $sourceRoot -Recurse -File |
            Where-Object { $_.FullName -notmatch "\\(\.git|\.venv[^\\]*|__pycache__|build|dist)\\" } |
            ForEach-Object { $_.FullName.Substring($sourceRoot.Length + 1) }
    }
    foreach ($relative in $files) {
        $source = Join-Path $sourceRoot $relative
        if (-not (Test-Path -LiteralPath $source -PathType Leaf)) {
            continue
        }
        $destination = Join-Path $nodeRoot $relative
        New-Item -ItemType Directory -Path (Split-Path -Parent $destination) -Force | Out-Null
        Copy-Item -LiteralPath $source -Destination $destination -Force
    }
}
Invoke-Checked $venvPython ($pip + @("-e", $nodeRoot)) "Installing the custom node package"

# --- XRT SDK ---------------------------------------------------------------
Write-Step "Configuring the XRT SDK"
if ($XrtSdkDirectory) {
    $xrtDirectory = (Resolve-Path -LiteralPath $XrtSdkDirectory).Path
    if (-not (Test-XrtSdk $xrtDirectory)) {
        throw "XrtSdkDirectory must contain include\xrt, lib and python\pyxrt.pyd: $xrtDirectory"
    }
}
else {
    $xrtDirectory = Join-Path $env:LOCALAPPDATA "AMD\xrt-$xrtVersion"
    if (-not (Test-XrtSdk $xrtDirectory)) {
        if (Test-Path -LiteralPath $xrtDirectory) {
            throw "Incomplete XRT SDK directory: $xrtDirectory. Remove it or pass -XrtSdkDirectory."
        }
        Install-XrtSdk $xrtDirectory
    }
}
Write-Host "XRT SDK: $xrtDirectory"
Copy-Item -LiteralPath (Join-Path $xrtDirectory "python\pyxrt.pyd") -Destination (Join-Path $venv "Lib\site-packages\pyxrt.pyd") -Force

# --- Launcher, runtime and configuration -----------------------------------
Write-Step "Writing the launcher and runtime configuration"
$launcher = @"
# $generatedMarker.
# Runtime settings are read from xdna-runtime\anima-xdna.json by the custom node.
`$ErrorActionPreference = "Stop"
Set-Location -LiteralPath `$PSScriptRoot
& (Join-Path `$PSScriptRoot ".venv\Scripts\python.exe") (Join-Path `$PSScriptRoot "main.py") $desktopArguments @args
exit `$LASTEXITCODE
"@
Write-GeneratedFile (Join-Path $InstallRoot "run-xdna.ps1") ($launcher.Replace("`r`n", "`n") + "`n")

$runtimeRoot = Join-Path $InstallRoot "xdna-runtime"
New-Item -ItemType Directory -Path $runtimeRoot -Force | Out-Null
if ($RuntimeProfile -eq "int8") {
    Write-Step "Installing the experimental INT8/AIR runtime bundle"
    $runtimeArguments = @{ ComfyUIRoot = $InstallRoot }
    if ($RuntimeBundlePath) {
        $runtimeArguments.BundlePath = (Resolve-Path -LiteralPath $RuntimeBundlePath).Path
    }
    & (Join-Path $nodeRoot "tools\install_int8_runtime.ps1") @runtimeArguments
}

$config = [ordered]@{
    schema_version = 1
    profile = $(if ($RuntimeProfile -eq "int8") { "int8-attn-l1k64-nq8pp" } else { "standard" })
    xrt_dev_dir = $xrtDirectory
    triton_cache_dir = "cache/triton"
}
if ($NumThreads) {
    $config.num_threads = $NumThreads
}
[System.IO.File]::WriteAllText((Join-Path $runtimeRoot "anima-xdna.json"), (($config | ConvertTo-Json) + "`n"), $utf8)

if ($ModelsDirectory) {
    $models = ([System.IO.Path]::GetFullPath($ModelsDirectory)).Replace("\", "/").Replace("'", "''")
    $yaml = @"
# $generatedMarker.
anima_xdna_models:
  base_path: '$models'
  diffusion_models: diffusion_models
  text_encoders: text_encoders
  vae: vae
  loras: loras
"@
    Write-GeneratedFile (Join-Path $InstallRoot "extra_model_paths.yaml") ($yaml.Replace("`r`n", "`n") + "`n")
}

$workflowDirectory = Join-Path $InstallRoot "user\default\workflows"
$workflow = Join-Path $workflowDirectory "Anima XDNA Cache-backed 1024.json"
if (-not (Test-Path -LiteralPath $workflow)) {
    New-Item -ItemType Directory -Path $workflowDirectory -Force | Out-Null
    Copy-Item -LiteralPath $workflowSource -Destination $workflow
}

# --- Verification ----------------------------------------------------------
if (-not $SkipChecks) {
    Write-Step "Probing the XDNA 2 NPU"
    $previousXrt = $env:XRT_DEV_DIR
    try {
        $env:XRT_DEV_DIR = $xrtDirectory
        Invoke-Checked (Join-Path $venv "Scripts\anima-xdna-probe.exe") @() "NPU probe"
    }
    finally {
        $env:XRT_DEV_DIR = $previousXrt
    }

    Write-Step "Loading ComfyUI and the custom node (--quick-test-for-ci)"
    $ErrorActionPreference = "Continue"
    Push-Location -LiteralPath $InstallRoot
    try {
        $log = & $venvPython main.py --cpu --quick-test-for-ci 2>&1 | ForEach-Object { "$_" }
        $exitCode = $LASTEXITCODE
    }
    finally {
        Pop-Location
        $ErrorActionPreference = "Stop"
    }
    $failed = @($log | Where-Object { $_ -match "IMPORT FAILED" -and $_ -match "anima-xdna-comfyui" })
    $configured = @($log | Where-Object { $_ -match "\[Anima XDNA\] Runtime config:" })
    if ($exitCode -ne 0 -or $failed -or -not $configured) {
        $log | Select-Object -Last 60 | Out-Host
        throw "ComfyUI could not load the Anima XDNA custom node with the generated configuration."
    }
    $configured | Out-Host
}

Write-Step "Done"
Write-Host @"
Installed Anima XDNA ($RuntimeProfile profile) into: $InstallRoot

Command line:  powershell -ExecutionPolicy Bypass -File "$InstallRoot\run-xdna.ps1"
Comfy Desktop: Menu > Add Existing Instance > select $InstallRoot (Git Clone).
               The .venv virtual environment is used as-is. In Manage > Startup Args set:
               $desktopArguments
Models are not downloaded. Place Anima, the Qwen text encoder and the Qwen Image VAE
in ComfyUI's model folders (or pass -ModelsDirectory), then open the
"Anima XDNA Cache-backed 1024" workflow.
"@
